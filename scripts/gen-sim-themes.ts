// Authoring-time generator of the S7 demo's themes (run by hand, never at build time):
//
//   node scripts/gen-sim-themes.ts [path/to/plexustyping]
//
// Runs the PlexusTyping app's own typingColors() (src/features/themes/colors.ts) on every built-in theme
// of its THEMES list (src/features/themes/themes.ts: PlexusTerm, the 56 imported palettes and the two
// high-contrast ones, 59 in all), and writes
// - public/sim/themes/<id>.json: the CSS variables of one theme, exactly as the app's applyTheme() sets them;
// - public/sim/themes/index.json and src/sim/personalize/themes.generated.ts: the themes' ids, real names,
//   dark flag and high-contrast flag, in the app's order (the island's select is server-rendered from it).
// The island fetches a theme file from the same origin only when the visitor chooses it.
// Node 24 runs this TypeScript file and the app's directly (type stripping); a resolve hook adds the `.ts`
// the app's extensionless imports leave out (Vite resolves them in the app).
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HOOKS = `
export async function resolve(specifier, context, next) {
  try {
    return await next(specifier, context);
  } catch (err) {
    if (err?.code === "ERR_MODULE_NOT_FOUND" && specifier.startsWith(".") && !/\\.[cm]?[jt]s$/.test(specifier))
      return next(specifier + ".ts", context);
    throw err;
  }
}`;

/** One theme as the island lists it. */
export interface ThemeInfo {
  id: string;
  name: string;
  dark: boolean;
  highContrast: boolean;
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const app = resolve(process.argv[2] ?? join(root, "../plexustyping"));
const commit = execFileSync("git", ["-C", app, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();

register(`data:text/javascript,${encodeURIComponent(HOOKS)}`);
const themesModule = pathToFileURL(join(app, "src/features/themes/themes.ts")).href;
const colorsModule = pathToFileURL(join(app, "src/features/themes/colors.ts")).href;
const { THEMES } = await import(themesModule);
const { typingColors } = await import(colorsModule);

const outDir = join(root, "public/sim/themes");
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const index: ThemeInfo[] = [];
for (const entry of THEMES as { id: string; name: string; dark: boolean; highContrast?: boolean }[]) {
  const vars: Record<string, string> = typingColors(entry);
  writeFileSync(join(outDir, `${entry.id}.json`), `${JSON.stringify(vars)}\n`);
  index.push({ id: entry.id, name: entry.name, dark: entry.dark, highContrast: entry.highContrast === true });
}
writeFileSync(join(outDir, "index.json"), `${JSON.stringify({ commit, themes: index })}\n`);

writeFileSync(
  join(root, "src/sim/personalize/themes.generated.ts"),
  `// Generated by scripts/gen-sim-themes.ts from the PlexusTyping app's src/features/themes/themes.ts\n` +
    `// (app commit ${commit}): every built-in theme, in the app's order. Colours: public/sim/themes/<id>.json.\n` +
    `// Do not edit by hand: re-run the generator.\n\n` +
    `export interface ThemeInfo {\n  id: string;\n  name: string;\n  dark: boolean;\n  highContrast: boolean;\n}\n\n` +
    `export const THEMES: ThemeInfo[] = [\n${index.map((t) => `  ${JSON.stringify(t)},`).join("\n")}\n];\n`,
);

console.log(`${readdirSync(outDir).length - 1} theme files from app commit ${commit}`);
