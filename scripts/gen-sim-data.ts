// Authoring-time generator of the S1 demo's keyboard data (run by hand, never at build time):
//
//   node scripts/gen-sim-data.ts [path/to/plexustyping]
//
// Reads the app's Spanish (Spain) layout, layouts/es-qwerty.toml, and writes
// - src/sim/data/es-qwerty.ts: the layout in the `Layout` shape the app's `get_layout` command returns
//   (camelCase, keys in code order, a missing layer as null), which the copied Keyboard.svelte draws;
// - src/sim/data/sequences.ts: for every char of the demo texts, the presses the app's `key_sequences`
//   command returns for it, computed with the port of Rust's `Layout::locate` (src/sim/keyboard/locate.ts).
// Node 24 runs this TypeScript file directly (type stripping).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DIAGNOSTIC_TEXT, TARGET_TEXT } from "../src/sim/data/texts.ts";
import { locate } from "../src/sim/keyboard/locate.ts";
import type { KeyLayers, Layout } from "../src/sim/keyboard/types.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const app = resolve(process.argv[2] ?? join(root, "../plexustyping"));
const source = "layouts/es-qwerty.toml";
const commit = execFileSync("git", ["-C", app, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();

/** TOML basic string body: the escapes the layout files use. */
const unescape = (s: string) => s.replace(/\\(["\\])/g, "$1");

/** The subset of TOML the layout files use: `name`, `dead_keys` and `[keys.Code]` tables of strings. */
function parseLayout(id: string, toml: string): Layout {
  let name = "";
  let deadKeys: string[] = [];
  const keys: Record<string, KeyLayers> = {};
  let current: KeyLayers | null = null;
  for (const raw of toml.split("\n")) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const table = /^\[keys\.(\w+)\]$/.exec(line);
    if (table) {
      current = { normal: null, shift: null, altgr: null };
      keys[table[1]!] = current;
      continue;
    }
    const pair = /^(\w+)\s*=\s*(.+)$/.exec(line);
    if (!pair) throw new Error(`unparsed line: ${line}`);
    const [, key = "", value = ""] = pair;
    const str = () => {
      const m = /^"((?:[^"\\]|\\.)*)"$/.exec(value);
      if (!m) throw new Error(`not a string: ${line}`);
      return unescape(m[1] ?? "");
    };
    if (current) {
      if (key !== "normal" && key !== "shift" && key !== "altgr") throw new Error(`unknown layer: ${line}`);
      const ch = str();
      if ([...ch].length !== 1) throw new Error(`not one char: ${line}`);
      current[key] = ch;
    } else if (key === "name") name = str();
    else if (key === "dead_keys") deadKeys = [...value.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => unescape(m[1] ?? ""));
    else throw new Error(`unknown field: ${line}`);
  }
  const sorted = Object.fromEntries(Object.keys(keys).sort().map((code) => [code, keys[code]!]));
  return { id, name, deadKeys, keys: sorted };
}

const layout = parseLayout("es-qwerty", readFileSync(join(app, source), "utf8"));
const banner = (what: string) =>
  `// Generated by scripts/gen-sim-data.ts from the PlexusTyping app's ${source} (app commit ${commit}).\n` +
  `// ${what}\n// Do not edit by hand: re-run the generator.\n`;

writeFileSync(
  join(root, "src/sim/data/es-qwerty.ts"),
  `${banner("The layout as the app's get_layout command returns it.")}import type { Layout } from "../keyboard/types";\n\n` +
    `export const ES_QWERTY: Layout = ${JSON.stringify(layout, null, 2)};\n`,
);

const chars = [...new Set([...DIAGNOSTIC_TEXT, ...TARGET_TEXT])].sort();
const sequences = Object.fromEntries(chars.map((ch) => [ch, locate(layout, ch)]));
writeFileSync(
  join(root, "src/sim/data/sequences.ts"),
  `${banner("Presses of each char of the demo texts, as the app's key_sequences command returns them.")}` +
    `import type { KeyPress } from "../keyboard/types";\n\n` +
    `export const KEY_SEQUENCES: Record<string, KeyPress[] | null> = ${JSON.stringify(sequences)};\n\n` +
    `/** The presses for each char of \`text\` (\`null\` if untypeable), like \`key_sequences\` for one text. */\n` +
    `export const sequencesFor = (text: string): (KeyPress[] | null)[] => [...text].map((ch) => KEY_SEQUENCES[ch] ?? null);\n`,
);
console.log(`es-qwerty: ${Object.keys(layout.keys).length} keys; sequences for ${chars.length} chars (app ${commit})`);
